package com.depromeet.piki.product.routing

// 도메인 하나를 어떻게 대하는가. 축은 이것 하나이고 값은 둘뿐이다 — 행이 없으면 "아직 판단하지 않음"이라
// 기본 흐름(정적 fetch -> 필요하면 브라우저 승격)을 그대로 탄다.
//
// 옛 ExtractionRoute 가 세 질문(등록을 받나 / 어떻게 가져오나 / 실측했나)에 한 축으로 답하다 모순 조합을
// 만들어냈던 것이 이 enum 을 값 둘로 좁힌 이유다. "어떻게 가져오나"는 추출 체인이 관측으로 스스로 정하고,
// 여기서는 "받을 것인가"와 "어디까지 허락됐나"만 답한다.
enum class DomainAccess {
    // 플랫폼의 명시적 허락을 받았다. 등록을 받고, 렌더 서비스의 우회 수단(지문 보정·프록시)까지 열린다.
    // 허락은 사람이 받아 오는 것이라 근거(permissionRef) 없이는 켤 수 없다(입력 경계가 강제).
    ALLOWED,

    // 얻을 수 없다고 판단한 도메인. 등록을 400 으로 거절하고, 이미 담긴 아이템의 재파싱도 요청을 보내지 않는다.
    // 차단당했다는 사실을 확인한 곳에 매번 다시 두드리지 않는다는 뜻이라, 최적화이자 계약이다.
    BLOCKED,
}
