package com.depromeet.piki.item.domain

// item 의 파싱 생애주기. 등록은 외부 LLM 추출(긴 latency)을 백그라운드로 미루므로,
// 클라이언트가 "담는 중 / 완성 / 등록 실패" 를 구분할 수 있도록 상태를 서버가 명시적으로 갖는다.
enum class ItemStatus {
    // 등록 직후 커밋된 상태(작업 큐 적재). 아직 디스패처가 집지 않아 파싱이 시작 전이다.
    // 작업의 진실 원천은 인메모리 큐가 아니라 이 DB 행이라, @Async 유실과 무관하게 마감 안에 슬롯이 나면 claim 된다.
    // 일시 오류로 결론 없이 끝난 실행이 소유권을 반납(release)하면 이 상태로 되돌아와 다시 집히기를 기다린다 —
    // 즉 PENDING 은 "아직 한 번도 안 한 일"뿐 아니라 "다시 해야 할 일"도 담는다.
    PENDING,

    // 디스패처가 claim 해 파싱이 진행 중. name·price·imageUrl 은 아직 비어 있다.
    // 프로세스가 죽어 반납조차 못 한 채 여기 갇힌 행은 recover 가 재실행으로 되살린다(execution at-least-once, #461).
    PROCESSING,

    // 파싱 완료. 추출된 상품 정보가 채워졌다.
    READY,

    // 파싱 실패. 세 갈래다: (1) 확정 실패 — 상품 페이지가 아니거나 추출값을 신뢰할 수 없음. 재시도해도 결과가 같으므로
    // 워커가 즉시 종결한다. (2) 실행 예산 소진 — 일시 외부 오류·크래시로 끝나지 않은 실행을 상한(MAX_ATTEMPTS)까지
    // 다시 해봤으나 끝내 완료하지 못함. (3) 마감 초과 — created_at 기준 상한을 넘김. 예산·박동과 무관한 벽시계라
    // **실행을 한 번도 못 한 PENDING** 도 여기로 온다(슬롯이 끝내 나지 않은 경우).
    // 셋 다 동기 400 이 아니라 상태로 표현해 클라이언트가 SSE 알림으로 인지한다.
    FAILED,
}
