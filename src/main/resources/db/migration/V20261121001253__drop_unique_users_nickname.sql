-- 프로필 닉네임 중복 허용(#1287). 전역 유일(#1018)을 기획이 걷어냈다.
--
-- 전역 유일의 실질 목적은 토너먼트 안에서 참여자를 구분하는 것이었는데, 그 구분은 참여 닉네임
-- (tournament_users.nickname)이 그 토너먼트 안에서만 유일하면 충족된다. 프로필 닉네임까지 하나의
-- 이름 공간으로 묶을 이유가 없어진다.
--
-- 이 인덱스를 떼면 users.nickname 에 인덱스가 남지 않는다. 떼도 되는 이유는 닉네임으로 users 를
-- 조회하는 경로가 이 PR 에서 전부 사라지기 때문이다 - 중복 검사(existsByNickname 계열)와 게스트
-- 닉네임 자동 생성의 소진 조회(findNicknamesIn)가 중복 허용으로 불필요해진다. 닉네임 조회가 다시
-- 필요해지면 그때 조회 전용 인덱스를 세운다(유일 제약이 아니라).
--
-- 되돌리기 어렵다. 유일 제약을 다시 걸려면 그사이 쌓인 중복 닉네임을 먼저 정리해야 한다.
-- 그래서 "되돌릴 길" 로 제약을 남겨 두지 않는다 - 중복을 허용하기로 한 결정이 곧 이 제약의 은퇴다.
--
-- ALGORITHM·LOCK 을 명시해 온라인으로 도는지 DB 가 검증하게 한다(#1246 과 같은 결).
ALTER TABLE users
    DROP INDEX uq_users_nickname,
    ALGORITHM = INPLACE,
    LOCK = NONE;
